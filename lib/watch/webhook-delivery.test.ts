import assert from "node:assert/strict";
import { createHmac, randomUUID } from "node:crypto";
import { createServer } from "node:http";
import { test } from "node:test";
import { and, eq, sql } from "drizzle-orm";

// Use an empty, isolated database: deliverOnce owns the whole pending outbox.
test("webhook lifecycle: signed alerts, retries, pauses, atomic rotation and reporting", { skip: !process.env.FLETCH_TEST_DATABASE_URL }, async function lifecycle(): Promise<void> {
  process.env.DATABASE_URL = process.env.FLETCH_TEST_DATABASE_URL;
  process.env.BETTER_AUTH_SECRET = "controlled-webhook-test-encryption-key";
  const { db, close } = await import("@/lib/db");
  const { user, watchers, webhookEndpoints, watcherDeliveries } = await import("@/lib/db/schema");
  const hooks = await import("@/lib/watch/webhooks");
  const { updateWatcher } = await import("@/lib/watch/create");
  const { deliverOnce } = await import("@/lib/watch/deliver");
  const owner = randomUUID(), stranger = randomUUID();
  const seen: { body: Record<string, unknown>; signature: string; raw: string }[] = [];
  let status = 204;
  const server = createServer(async function receive(request, response): Promise<void> {
    const parts: Buffer[] = [];
    for await (const part of request) parts.push(Buffer.from(part));
    const raw = Buffer.concat(parts).toString();
    seen.push({ body: JSON.parse(raw), signature: String(request.headers["x-fletch-signature"]), raw });
    response.writeHead(status, { "retry-after": "60", location: "/redirect-must-not-be-followed" });
    response.end();
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const address = server.address();
  assert.ok(address && typeof address === "object");
  const url = `http://127.0.0.1:${address.port}/receive`;
  try {
    const pending = await db.select({ id: watcherDeliveries.id }).from(watcherDeliveries).where(eq(watcherDeliveries.status, "pending"));
    assert.equal(pending.length, 0, "Requires isolated outbox");
    await db.insert(user).values([{ id: owner }, { id: stranger }]);
    const hook = await hooks.createWebhookEndpoint(owner, { url, name: "Controlled receiver" });
    assert.equal(await hooks.getWebhookEndpoint(stranger, hook.id), null);
    await assert.rejects(hooks.sendWebhookPing(stranger, hook.id), { name: "WebhookNotFoundError" });
    await assert.rejects(hooks.updateWebhookEndpoint(stranger, hook.id, { rotateSecret: true }), { name: "WebhookNotFoundError" });
    await assert.rejects(hooks.deleteWebhookEndpoint(stranger, hook.id), { name: "WebhookNotFoundError" });
    const first = await hooks.sendWebhookPing(owner, hook.id);
    assert.equal(first.ok, true);
    assert.equal(seen[0].body.kind, "ping");
    assert.equal(seen[0].body.watcher, null);
    let endpoint = await hooks.getWebhookEndpoint(owner, hook.id);
    assert.ok(endpoint?.lastTestAt);
    assert.equal(endpoint.lastAlertAt, null, "A test cannot claim an alert delivery");
    const watcherId = randomUUID(), manualId = randomUUID();
    const base = { userId: owner, name: "Catalog changes", chainId: 4663, address: "0x" + "a".repeat(40), threshold: "0", kind: "listing_event" as const, delivery: "webhook" as const, webhookId: hook.id };
    await db.insert(watchers).values([{ ...base, id: watcherId }, { ...base, id: manualId }]);
    const deliveryId = randomUUID();
    await db.insert(watcherDeliveries).values({ id: deliveryId, userId: owner, watcherId, txHash: randomUUID(), logIndex: 0, blockNumber: BigInt(1), blockHash: "controlled", payload: { kind: "authority", title: "TEST: Price feed only in the Robinhood app", registryUrl: "/registry/changes" } });
    await hooks.setWebhookEndpointEnabled(owner, hook.id, false);
    await updateWatcher(owner, manualId, { enabled: false });
    await assert.rejects(updateWatcher(owner, watcherId, { enabled: true }), { name: "InvalidDeliveryError" });
    await assert.rejects(hooks.sendWebhookPing(owner, hook.id), { name: "WebhookDisabledError" });
    const beforeCount = seen.length;
    await deliverOnce();
    let [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "pending");
    assert.equal(row.attempts, 0);
    assert.equal(seen.length, beforeCount, "A disabled endpoint consumes no attempt");
    const fillers = Array.from({ length: 5 }, () => randomUUID());
    await db.insert(watchers).values(fillers.map((id) => ({ ...base, id, webhookId: null, delivery: "telegram" as const })));
    const [beforeSecret] = await db.select().from(webhookEndpoints).where(eq(webhookEndpoints.id, hook.id));
    await assert.rejects(hooks.updateWebhookEndpoint(owner, hook.id, { enabled: true, rotateSecret: true }), { name: "WatchLimitError" });
    const [afterSecret] = await db.select().from(webhookEndpoints).where(eq(webhookEndpoints.id, hook.id));
    assert.equal(afterSecret.secretEnc, beforeSecret.secretEnc, "Failed enable cannot rotate a secret");
    assert.equal(afterSecret.enabled, false);
    await db.delete(watchers).where(and(eq(watchers.userId, owner), eq(watchers.delivery, "telegram")));
    await hooks.setWebhookEndpointEnabled(owner, hook.id, true);
    const [manual] = await db.select().from(watchers).where(eq(watchers.id, manualId));
    assert.equal(manual.enabled, false, "A manual pause survives endpoint enable");
    status = 500;
    await deliverOnce();
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "pending");
    assert.equal(row.attempts, 1);
    status = 429;
    await db.update(watcherDeliveries).set({ nextAttemptAt: new Date(0) }).where(eq(watcherDeliveries.id, deliveryId));
    await deliverOnce();
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.ok(row.nextAttemptAt.getTime() > Date.now() + 55_000, "Retry-After is respected");
    assert.equal(row.attempts, 2);
    status = 204;
    await db.update(watcherDeliveries).set({ nextAttemptAt: new Date(0) }).where(eq(watcherDeliveries.id, deliveryId));
    await deliverOnce();
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "sent");
    assert.ok(row.sentAt);
    const alerts = seen.filter((request) => request.body.id === deliveryId);
    assert.equal(alerts.length, 3);
    assert.deepEqual(alerts.map((request) => request.body.attempt), [1, 2, 3]);
    assert.deepEqual(alerts[2].body.watcher, { id: watcherId, name: "Catalog changes", kind: "listing_event" });
    for (const request of seen) {
      const t = request.signature.split(",")[0].slice(2);
      const signature = createHmac("sha256", hook.secret).update(`${t}.${request.raw}`).digest("hex");
      assert.equal(request.signature, `t=${t},v1=${signature}`);
    }
    endpoint = await hooks.getWebhookEndpoint(owner, hook.id);
    assert.equal(endpoint?.lastAlertStatus, 204);
    const alertAt = endpoint?.lastAlertAt?.getTime();
    status = 503;
    await hooks.sendWebhookPing(owner, hook.id);
    endpoint = await hooks.getWebhookEndpoint(owner, hook.id);
    assert.equal(endpoint?.lastAlertAt?.getTime(), alertAt, "Failed tests preserve alert reporting");
    assert.equal(endpoint?.lastTestStatus, 503);
    const rotated = await hooks.rotateWebhookSecret(owner, hook.id);
    assert.notEqual(rotated.secret, hook.secret);
    assert.equal(rotated.lastTestAt, null, "New signing secret must be tested again");
    assert.equal(rotated.lastAlertStatus, 204);
    status = 302;
    const countBeforeRedirect = seen.length;
    const redirect = await hooks.sendWebhookPing(owner, hook.id);
    assert.equal(redirect.ok, false);
    assert.equal(redirect.status, 302);
    assert.equal(seen.length, countBeforeRedirect + 1);
    await db.update(watcherDeliveries).set({ status: "held", sentAt: null, attempts: 0 }).where(eq(watcherDeliveries.id, deliveryId));
    const replacement = await hooks.createWebhookEndpoint(owner, { url });
    await updateWatcher(owner, watcherId, { webhookId: replacement.id });
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "pending", "Reassignment queues recent held matches");
    await db.update(watcherDeliveries).set({ attempts: 7 }).where(eq(watcherDeliveries.id, deliveryId));
    status = 500;
    await deliverOnce();
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "failed");
    assert.equal(row.attempts, 8);
    await db.update(watcherDeliveries).set({ status: "pending", nextAttemptAt: sql`now()` }).where(eq(watcherDeliveries.id, deliveryId));
    await hooks.deleteWebhookEndpoint(owner, replacement.id);
    [row] = await db.select().from(watcherDeliveries).where(eq(watcherDeliveries.id, deliveryId));
    assert.equal(row.status, "failed");
    const [paused] = await db.select().from(watchers).where(eq(watchers.id, watcherId));
    assert.equal(paused.enabled, false);
    assert.equal(paused.webhookId, null);
    await assert.rejects(updateWatcher(owner, watcherId, { enabled: true }), { name: "InvalidDeliveryError" });
    console.log("Controlled receiver: ping and watcher metadata verified; 500 → 429 → 204 with stable delivery ID, signatures valid on all attempts. No external messages sent.");
  } finally {
    await db.delete(user).where(eq(user.id, owner));
    await db.delete(user).where(eq(user.id, stranger));
    await close();
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
});
