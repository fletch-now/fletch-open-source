import { createHash } from "node:crypto";

export function isRegistryChangesPage(html) {
  return /<main(?:\s|>)/.test(html)
    && /<h1(?:\s|>)/.test(html)
    && html.includes('aria-label="Filter registry changes"');
}

export function validateRelease(release) {
  if (!/^[a-z0-9][a-z0-9-]{5,63}$/.test(release.id))
    throw Error("Invalid release ID");
  if (
    !/^\/opt\/fletch\/[a-zA-Z0-9/_-]+$/.test(release.root) ||
    release.root.includes("..")
  )
    throw Error("Release must use an immutable path under /opt/fletch");
  if (
    !Number.isInteger(release.port) ||
    release.port < 3001 ||
    release.port > 3099
  )
    throw Error("Release port must be between 3001 and 3099");
}

